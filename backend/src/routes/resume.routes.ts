import { Router } from 'express';
import multer from 'multer';
import type { RequestHandler, NextFunction } from 'express';

import { authenticate } from '../middleware/auth.middleware.js';
import { uploadResume } from '../config/upload.js';

import {
  uploadResumeController,
  getUserResumesController,
  getResumeDetailsController,
  previewResumeController,
  downloadResumeController,
  renameResumeController,
  deleteResumeController,
} from '../controllers/resume.controller.js';

const router = Router();

// All resume routes require authentication.
router.use(authenticate);

// Handle errors generated by Multer before the controller runs.
const handleResumeUpload: RequestHandler = (req, res, next) => {
  uploadResume.single('resume')(req, res, (error?: unknown) => {
    if (!error) {
      next();
      return;
    }

    if (error instanceof multer.MulterError) {
      const statusCode =
        error.code === 'LIMIT_FILE_SIZE' ? 413 : 400;

      res.status(statusCode).json({
        success: false,
        message:
          error.code === 'LIMIT_FILE_SIZE'
            ? 'File size exceeds the 5 MB limit.'
            : 'Invalid file upload. Please try again.',
      });

      return;
    }

    const message =
      error instanceof Error
        ? error.message
        : 'Invalid file upload.';

    res.status(400).json({
      success: false,
      message,
    });
  });
};

// Upload a new resume.
router.post(
  '/upload',
  handleResumeUpload,
  uploadResumeController,
);

// Get all resumes belonging to the authenticated user.
router.get(
  '/',
  getUserResumesController,
);

// Preview original PDF resume.
router.get(
  '/:resumeId/preview',
  previewResumeController,
);

// Download original PDF or DOCX resume.
router.get(
  '/:resumeId/download',
  downloadResumeController,
);

// Rename an existing resume.
router.patch(
  '/:resumeId',
  renameResumeController,
);

// Delete an existing resume.
router.delete(
  '/:resumeId',
  deleteResumeController,
);

// Get one resume with its extracted text.
router.get(
  '/:resumeId',
  getResumeDetailsController,
);

export default router;